//! `shellflow unit render` — generate a unit's service drop-in.
//!
//! Forty-three of the repository's unit files carry the same
//! `ExecStartPre=/usr/local/bin/shellflow cred-env render …` line, fourteen
//! carry the same `ExecStartPost=… systemd-notify --status=…` line, and every
//! credentialed unit spells out its `LoadCredentialEncrypted=` keys by hand.
//! Those three blocks are identical in shape and differ only in the service's
//! facts — so they are **generated** from the service manifest instead of
//! copied.
//!
//! The output is a **drop-in**, not a rewritten unit: systemd merges
//! `services/<svc>/<svc>.service.d/10-shellflow.conf` over the unit, so the
//! unit file keeps the parts that are service-specific and loses the parts
//! that are not.
//!
//! The generator is also the place where the shared hardening becomes a
//! default: the repository's `services/_common/10-hardening.conf` is included
//! in the generated drop-in when it exists, so a service cannot forget it.

use std::path::{Path, PathBuf};

use crate::manifest::ServiceManifest;

/// The name of the generated drop-in inside a service directory.
///
/// The file is numbered **after** the shared hardening drop-in
/// (`10-hardening.conf`), so the two live side by side in the same
/// directory: the hardening is the repository's single copy, and this file
/// carries only what is specific to the service.
pub(crate) const DROPIN_NAME: &str = "20-shellflow.conf";

/// The shared hardening drop-in, relative to the repository root.
///
/// It is installed into **every** unit's drop-in directory by the deploy
/// playbook, so the hardening is a default rather than an opt-in — and it
/// exists in exactly one place in the repository, so changing it changes it
/// everywhere.
pub(crate) const HARDENING_FILE: &str = "services/_common/10-hardening.conf";

/// The name of the shared hardening drop-in, as installed on the target.
pub(crate) const HARDENING_NAME: &str = "10-hardening.conf";

/// The generated drop-in of one service.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub(crate) struct RenderedUnit {
    /// The drop-in's text, ready to be written.
    pub text: String,
    /// The credential keys the unit declares.
    pub credential_keys: Vec<String>,
}

/// Generate a service's drop-in.
///
/// The credential keys come from the sealed env file the manifest names: the
/// file is decrypted to read its **key set** (never the values), so the
/// generated `LoadCredentialEncrypted=` lines always agree with the store the
/// deploy seals.
///
/// # Errors
///
/// Returns [`UnitError`] when the manifest names no credential file, when the
/// sealed file cannot be read, or when the manifest lacks the facts the
/// generated lines need.
pub(crate) fn render(manifest: &ServiceManifest, credential_keys: &[String]) -> RenderedUnit {
    let mut text = String::new();
    text.push_str("# Generated by `shellflow unit render` — do not edit by hand.\n");
    text.push_str("#\n");
    text.push_str("# The credential wiring, the configuration render, and the version status\n");
    text.push_str("# line are the same for every service; generating them keeps them from\n");
    text.push_str("# drifting apart, and keeps the unit file free of copy-paste.\n");
    text.push_str("#\n");
    text.push_str("# The shared hardening is NOT here: it is one file in the repository\n");
    text.push_str("# (services/_common/10-hardening.conf), installed into this directory\n");
    text.push_str("# under the name 10-hardening.conf by the deploy playbook.\n");

    text.push_str("\n[Service]\n");

    // The credential keys. A manifest that names them wins over the sealed
    // file's key set: a unit that shares a store with a sibling must see
    // only its own keys, and a unit whose service borrows another service's
    // store declares no sealed file of its own.
    let selected: Vec<String> = if manifest.credentials.is_empty() {
        credential_keys.to_vec()
    } else {
        manifest.credentials.clone()
    };
    let mut keys = Vec::new();
    let store = manifest.store_dir();
    for key in &selected {
        text.push_str(&format!(
            "LoadCredentialEncrypted={key}:{store}/{key}\n",
            store = store.display()
        ));
        keys.push(key.clone());
    }

    // The configuration renders.
    for (template, target) in &manifest.renders {
        text.push_str(&format!(
            "ExecStartPre=/usr/local/bin/shellflow cred-env render {template} {target}\n"
        ));
    }

    // No version status line: reporting it needs `systemd-notify`, and the
    // notify socket is not there for an `ExecStartPost` -- not on a
    // `Type=simple` unit and, as a live deploy proved, not on a `Type=notify`
    // unit either. The call fails, and a failing control process takes the
    // just-started service down with it. The version stays one command away
    // (`<binary> -V`); the drop-in does not try to be clever.

    RenderedUnit { text, credential_keys: keys }
}

/// The path of a unit's generated drop-in.
#[must_use]
pub(crate) fn dropin_path(repo: &Path, service: &str, unit: &str) -> PathBuf {
    repo.join("services").join(service).join(format!("{unit}.service.d")).join(DROPIN_NAME)
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::{DROPIN_NAME, dropin_path, render};
    use crate::manifest::ServiceManifest;

    fn manifest(text: &str) -> ServiceManifest {
        ServiceManifest::parse("dufs", text).expect("manifest")
    }

    #[test]
    fn a_dropin_is_written_beside_the_unit() {
        let path = dropin_path(Path::new("/repo"), "dufs", "dufs");
        assert!(path.ends_with("dufs.service.d/20-shellflow.conf"), "{path:?}");
        assert!(path.to_string_lossy().contains(DROPIN_NAME));
    }

    #[test]
    fn a_manifest_without_credentials_generates_only_the_render_line() {
        let manifest = manifest(
            "host = \"api\"\nunit = \"dufs.service\"\n\
             binary = \"/opt/dufs/bin/dufs\"\n\
             type = \"notify\"\n\
             [render]\ntemplate = \"/t.tmpl\"\ntarget = \"/run/dufs/c.yaml\"\n",
        );
        let rendered = render(&manifest, &[]);
        assert!(rendered.credential_keys.is_empty());
        assert!(
            rendered.text.contains(
                "ExecStartPre=/usr/local/bin/shellflow cred-env render /t.tmpl /run/dufs/c.yaml"
            ),
            "{}",
            rendered.text
        );
        assert!(!rendered.text.contains("ExecStartPost"), "{}", rendered.text);
    }

    #[test]
    fn no_unit_reports_its_version_through_the_dropin() {
        // Reporting needs `systemd-notify`, and the notify socket is not
        // there for an `ExecStartPost` -- a live deploy proved it fails on a
        // `Type=notify` unit too, and a failing control process takes the
        // just-started service down with it.
        let manifest = manifest(
            "host = \"api\"\nunit = \"dufs.service\"\n\
             binary = \"/opt/dufs/bin/dufs\"\n\
             type = \"notify\"\n",
        );
        let rendered = render(&manifest, &[]);
        assert!(!rendered.text.contains("systemd-notify"), "{}", rendered.text);
        assert!(!rendered.text.contains("ExecStartPost"), "{}", rendered.text);
    }

    #[test]
    fn the_shared_hardening_stays_in_one_place() {
        // The generated drop-in carries only what is service-specific: the
        // shared hardening is one file in the repository, installed into
        // every unit's drop-in directory by the playbook. Embedding it here
        // would put 78 copies of the same 33 lines into the repository.
        let manifest = manifest("host = \"api\"\nunit = \"dufs.service\"\n");
        let rendered = render(&manifest, &[]);
        assert!(!rendered.text.contains("NoNewPrivileges"), "{}", rendered.text);
        assert!(!rendered.text.contains("ProtectSystem"), "{}", rendered.text);
        assert!(rendered.text.contains("10-hardening.conf"), "{}", rendered.text);
    }

    #[test]
    fn a_render_without_its_pair_is_rejected_at_parse_time() {
        // The manifest is the source of truth, so an incomplete `[render]`
        // is caught before anything is generated.
        let err = ServiceManifest::parse(
            "dufs",
            "host = \"api\"\nunit = \"dufs.service\"\n\
             [render]\ntemplate = \"/t.tmpl\"\n",
        )
        .unwrap_err();
        assert!(err.to_string().contains("no `render.target` string"), "{err}");
    }
}
